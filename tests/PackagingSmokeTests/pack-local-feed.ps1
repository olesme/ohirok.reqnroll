<#
.SYNOPSIS
  Packs every package under src/ into tests/PackagingSmokeTests/.localfeed for the packaging smoke tests.

.DESCRIPTION
  The smoke tests consume the plugins exclusively through PackageReference, so they need a real feed
  to restore from. This script produces one. It is called three ways, and all three produce identical
  packages:

    - automatically, by Directory.Build.targets, when a smoke project is restored or built and the feed
      is missing or older than the sources under src/;
    - by scripts/test-packages.ps1 (the one-command local/CI entry point);
    - by publish.yml, which packs the release artifacts separately and points -FeedSource at them.

  The feed is wiped before packing: a stale nupkg left behind from an earlier pack is the one failure
  mode that would make a smoke run pass against code that no longer exists.

  Every project under src/ is packed, exactly like publish.yml does, so a newly added package is
  covered without editing this script.

.PARAMETER Version
  Package version to stamp. Must match OhirokSmokeVersion (see Directory.Build.props).

.PARAMETER Configuration
  Build configuration to pack.

.PARAMETER Force
  Repack even when the feed is up to date.

.PARAMETER IfStale
  Only pack when the feed is missing or older than the newest source file. Used by the MSBuild hook.
#>
[CmdletBinding()]
param(
    [string]$Version = '9999.0.0-smoke',
    [string]$Configuration = 'Release',
    [switch]$Force,
    [switch]$IfStale
)

$ErrorActionPreference = 'Stop'

$smokeRoot = $PSScriptRoot
$repoRoot = (Resolve-Path (Join-Path $smokeRoot '..\..')).Path
$srcRoot = Join-Path $repoRoot 'src'
$feed = Join-Path $smokeRoot '.localfeed'
$stamp = Join-Path $feed '.stamp'

function Get-NewestInputTime {
    $inputs = @(Get-ChildItem $srcRoot -Recurse -File |
        Where-Object { $_.FullName -notmatch '[\\/](bin|obj)[\\/]' })
    $inputs += Get-Item (Join-Path $repoRoot 'Directory.Build.props'), (Join-Path $repoRoot 'GeneratorPluginPackaging.targets')
    ($inputs | Measure-Object LastWriteTimeUtc -Maximum).Maximum
}

function Test-FeedFresh {
    if (-not (Test-Path $stamp)) { return $false }
    if ((Get-Content $stamp -Raw).Trim() -ne $Version) { return $false }
    (Get-Item $stamp).LastWriteTimeUtc -ge (Get-NewestInputTime)
}

# Several smoke projects restore in parallel and each one triggers the MSBuild hook. Only one may pack;
# the rest wait and then find the feed fresh.
$mutex = [System.Threading.Mutex]::new($false, 'Global\OhirokPackagingSmokeFeed')
[void]$mutex.WaitOne()
try {
    if ($IfStale -and -not $Force -and (Test-FeedFresh)) {
        Write-Host "Ohirok smoke feed is up to date ($Version)." -ForegroundColor DarkGray
        return
    }

    $projects = Get-ChildItem $srcRoot -Recurse -Filter *.csproj |
        Where-Object { $_.FullName -notmatch '[\\/](bin|obj)[\\/]' } |
        ForEach-Object FullName

    if (Test-Path $feed) {
        Remove-Item $feed -Recurse -Force
    }
    New-Item -ItemType Directory -Path $feed | Out-Null

    # One solution over every src project, so the whole set packs in a single parallel build.
    $work = Join-Path ([System.IO.Path]::GetTempPath()) "ohirok-pack-$PID"
    New-Item -ItemType Directory -Path $work -Force | Out-Null
    try {
        dotnet new sln -n packages -o $work --format slnx | Out-Null
        $sln = Join-Path $work 'packages.slnx'
        dotnet sln $sln add @projects | Out-Null
        if ($LASTEXITCODE -ne 0) { throw 'could not assemble the pack solution' }

        Write-Host "Packing $($projects.Count) projects from src/ -> $Version" -ForegroundColor Cyan
        # The smoke packages get a pinned version of their own, never a real release number.
        dotnet pack $sln -c $Configuration -o $feed "-p:Version=$Version" "-p:PackageVersion=$Version" -nologo
        if ($LASTEXITCODE -ne 0) { throw 'pack failed' }
    }
    finally {
        Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue
    }

    # A smoke project restoring an Ohirok package from the global cache instead of this feed would
    # silently test the wrong bits, so drop any cached copy of the version just packed.
    $cache = if ($env:NUGET_PACKAGES) { $env:NUGET_PACKAGES } else { Join-Path $HOME '.nuget/packages' }
    if (Test-Path $cache) {
        Get-ChildItem $cache -Directory -Filter 'ohirok.*' | ForEach-Object {
            $stale = Join-Path $_.FullName $Version
            if (Test-Path $stale) {
                Remove-Item $stale -Recurse -Force
            }
        }
    }

    # Leave every smoke project in the state of a fresh clone. Reqnroll's up-to-date check does not track
    # the generator plugins, so code-behind generated by the previous packages would survive a repack; and a
    # leftover obj/ makes even `dotnet restore` run code generation before the new packages are extracted,
    # producing code-behind with no plugin in it that the following build then treats as up to date.
    Get-ChildItem $smokeRoot -Recurse -Filter *.feature.cs |
        Where-Object { $_.FullName -notmatch '[\\/](bin|obj)[\\/]' } |
        Remove-Item -Force
    Get-ChildItem $smokeRoot -Directory |
        ForEach-Object { Join-Path $_.FullName 'bin'; Join-Path $_.FullName 'obj' } |
        Where-Object { Test-Path $_ } |
        ForEach-Object {
            $dir = $_
            for ($attempt = 1; ; $attempt++) {
                try { Remove-Item $dir -Recurse -Force -ErrorAction Stop; break }
                catch {
                    if ($attempt -ge 5) {
                        throw "cannot clean '$dir' - a process holds files in it (an IDE with the smoke projects loaded rebuilds them in the background; close it or unload those projects). $($_.Exception.Message)"
                    }
                    Start-Sleep -Milliseconds 500
                }
            }
        }

    Set-Content $stamp $Version -NoNewline
    Write-Host "Feed ready: $feed" -ForegroundColor Green
}
finally {
    $mutex.ReleaseMutex()
    $mutex.Dispose()
}
